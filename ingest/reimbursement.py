"""Read the MoH reimbursement catalogue PDFs (Κατάλογος Αποζημιούμενων Φαρμάκων).

The catalogue is published only as PDF, generated by JasperReports with a fixed layout
(A4 landscape, DejaVu Sans). Every text line is classified by colour, font and indent:

  title (11pt) and the three-line column header in the grey band  -> page furniture
  black bold, indent 20/24/28/32/36, starts with an ATC code       -> ATC heading, level 1-5
  green                                                            -> group heading ("G01 ...")
  red                                                              -> route of administration
  light blue, may wrap over several lines                          -> restriction note
  black with regular-weight characters                             -> package row

Headings nest as ATC1 > ATC2 > ATC3 > ATC4 > group > route > ATC5 > rows. A restriction
note belongs to the heading right above it (indent 40 under ATC4/group/route, indent 36
under ATC5) and applies to every row until that heading's group ends.

Anything that does not fit this picture raises CatalogueError: a layout change must fail
loudly, not shift values into the wrong field. Rows that parse but contradict themselves
raise AmbiguousRow, or go to `issues` for manual review when a list is given.
"""

from __future__ import annotations

import argparse
import csv
import re
from dataclasses import dataclass, field, fields
from pathlib import Path

LISTS = ("main", "n3816")

# Data columns as (field, x0 in pt). The report engine clips every value to its column,
# so a character belongs to the last column that starts at or before its x0.
_COLUMNS = (
    ("atc", 36.0),
    ("eof_code", 76.0),
    ("flag_s", 125.0),
    ("name_pdf", 132.0),
    ("dose_form", 188.0),
    ("strength", 252.0),
    ("flag_t", 317.0),
    ("pack", 327.0),
    ("dispensing", 383.0),
    ("mah_pdf", 483.0),
    ("ddd", 593.0),
    ("ddd_unit", 617.0),
    ("daily_doses_per_pack", 641.0),
    ("daily_cost", 681.0),
    ("retail_in_list", 729.0),
    ("reimbursement_price", 779.0),
)
_RIGHT_EDGE = 837.0  # right edge of the grey header band
_X_TOL = 0.5

# Column titles (x0, text) of the three header lines, checked on every page.
_HEADER = (
    ((132.0, "ΟΝΟΜΑΣΙΑ"), (188.0, "ΦΑΡΜΑΚΕΥΤΙΚΗ"), (483.0, "ΚΑΤΟΧΟΣ ΑΔΕΙΑΣ")),
    (
        (36.0, "ATC"),
        (76.0, "ΚΩΔΙΚΟΣ"),
        (125.0, "Σ"),
        (252.0, "ΠΕΡΙΕΚΤΙΚΟΤΗΤΑ"),
        (319.9, "Τ"),
        (327.0, "ΣΥΣΚΕΥΑΣΙΑ"),
        (383.0, "ΤΡΟΠΟΣ ΔΙΑΘΕΣΗΣ"),
        (593.0, "DDD"),
        (617.0, "ΜΟΝ"),
        (641.0, "ΑΗΔ"),
        (681.0, "ΚΗΘ"),
        (729.0, "ΛΙΑΝΙΚΗ"),
        (779.0, "ΑΠΟΖΗΜ."),
    ),
    ((132.0, "ΠΡΟΪΟΝΤΟΣ"), (188.0, "ΜΟΡΦΗ"), (483.0, "ΚΥΚΛΟΦΟΡΙΑΣ")),
)

# Text colours (non-stroking RGB) that carry meaning in the report.
_PALETTE = {
    "black": (0.0, 0.0, 0.0),
    "route": (1.0, 0.0549, 0.0392),
    "group": (0.0392, 0.5333, 0.2549),
    "restriction": (0.3608, 0.7647, 0.9804),
}
_TITLE_SIZE = 9.0  # the page title is 11pt, everything else 6-8pt
_LINE_TOL = 0.5  # characters of one line share the same top
_WRAP_GAP = 8.0  # wrapped lines of one note are 7pt apart, separate lines >= 9.5pt
_WORD_GAP = 1.0  # a horizontal gap wider than this is a space

# Heading levels, outer to inner.
_LEVELS = ("atc1", "atc2", "atc3", "atc4", "group", "route", "atc5")
_ATC_INDENT = {20.0: "atc1", 24.0: "atc2", 28.0: "atc3", 32.0: "atc4", 36.0: "atc5"}
_RESTRICTION_INDENT = {"atc4": 40.0, "group": 40.0, "route": 40.0, "atc5": 36.0}
_ATC_TOKEN = re.compile(r"[A-Z][0-9A-Za-z-]*")


class CatalogueError(ValueError):
    """Layout or row that cannot be read with confidence. Always fatal."""


class AmbiguousRow(ValueError):
    """Row that parses but whose values contradict each other."""


@dataclass
class ReimbursementRow:
    eof_code: str
    list_name: str  # "main" or "n3816"
    atc: str
    name_pdf: str  # truncated in the PDF; full names come from the price list
    dose_form: str
    strength: str
    pack: str
    dispensing: str
    mah_pdf: str
    ddd: float | None  # None when printed as 0 (not set, or below 3-decimal precision)
    ddd_unit: str | None
    daily_doses_per_pack: float | None  # ΑΗΔ, None when printed as 0
    daily_cost: float | None  # ΚΗΘ = ΛΙΑΝΙΚΗ / ΑΗΔ, None when printed as 0
    retail_in_list: float
    reimbursement_price: float
    flag_s: str  # raw, meaning unknown
    flag_t: str  # raw, meaning unknown
    route_group: str | None
    therapeutic_group: str | None
    restrictions: list[str] = field(default_factory=list)
    page: int = 0  # 1-based page of the PDF the row was read from


@dataclass
class _Heading:
    label: str  # full heading text, e.g. "A02BC01 OMEPRAZOLE"
    restrictions: list[str] = field(default_factory=list)

    @property
    def code(self) -> str:
        return self.label.split()[0]


# decimal separator -> number pattern; the other separator may only group thousands
_NUMBER = {
    d: re.compile(rf"\d{{1,3}}(?:{re.escape(t)}\d{{3}})+{re.escape(d)}\d+|\d+{re.escape(d)}\d+")
    for d, t in ((".", ","), (",", "."))
}


def parse_number(text: str, decimal: str) -> float:
    """Parse a number printed with the declared decimal separator.

    The other separator may group thousands ('1,234.56' or '1.234,56'). A decimal part is
    required: every numeric column of the catalogue prints one, so '6.01' read as
    decimal=',' (or '4.865,32' as '.') fails instead of being guessed.
    """
    if decimal not in _NUMBER:
        raise ValueError(f"decimal must be '.' or ',', not {decimal!r}")
    if not _NUMBER[decimal].fullmatch(text):
        raise CatalogueError(f"number {text!r} does not match decimal separator {decimal!r}")
    thousands = "," if decimal == "." else "."
    return float(text.replace(thousands, "").replace(decimal, "."))


def _colour(c: dict) -> str:
    col = c.get("non_stroking_color")
    if col is not None and len(col) == 1:
        col = (col[0],) * 3
    for name, ref in _PALETTE.items():
        if col is not None and len(col) == 3 and all(abs(a - b) < 0.01 for a, b in zip(col, ref)):
            return name
    raise CatalogueError(f"unexpected text colour {col!r} for {c['text']!r}")


def _lines(chars: list[dict]) -> list[list[dict]]:
    """Group the visible characters of a page into lines, top to bottom, left to right."""
    out: list[list[dict]] = []
    for c in sorted((c for c in chars if not c["text"].isspace()), key=lambda c: (c["top"], c["x0"])):
        if out and c["top"] - out[-1][0]["top"] <= _LINE_TOL:
            out[-1].append(c)
        else:
            out.append([c])
    for line in out:
        line.sort(key=lambda c: c["x0"])
    return out


def _text(chars: list[dict]) -> str:
    parts: list[str] = []
    prev = None
    for c in chars:
        if prev is not None and c["x0"] - prev > _WORD_GAP:
            parts.append(" ")
        parts.append(c["text"])
        prev = c["x1"]
    return " ".join("".join(parts).split())


def _matches(line: list[dict], titles) -> bool:
    for x, title in titles:
        start = next((i for i, c in enumerate(line) if abs(c["x0"] - x) <= 1.0), None)
        want = title.replace(" ", "")
        if start is None or "".join(c["text"] for c in line[start : start + len(want)]) != want:
            return False
    return True


def _strip_header(lines: list[list[dict]], page: int) -> tuple[list[list[dict]], str | None]:
    """Remove title and column header; return the content lines and the page title."""
    for i in range(1, len(lines) - 1):
        if all(_matches(lines[i + k], _HEADER[k + 1]) for k in (-1, 0, 1)):
            break
    else:
        raise CatalogueError(f"page {page}: column header not found")
    title = None
    for line in lines[: i - 1]:
        if line[0]["size"] < _TITLE_SIZE or title is not None:
            raise CatalogueError(f"page {page}: unexpected text above the header: {_text(line)!r}")
        title = _text(line)
    return lines[i + 2 :], title


def _classify(line: list[dict], page: int) -> tuple[str, float]:
    """Return (kind, indent): kind is a heading level, 'restriction' or 'row'."""
    colours = {_colour(c) for c in line}
    indent = round(line[0]["x0"], 1)
    if len(colours) != 1:
        raise CatalogueError(f"page {page}: mixed colours in line {_text(line)!r}")
    colour = colours.pop()
    if colour != "black":
        return colour, indent
    if any("Bold" not in c["fontname"] for c in line):
        return "row", indent
    level = _ATC_INDENT.get(indent)
    if level is None or not _ATC_TOKEN.match(_text(line)):
        raise CatalogueError(f"page {page}: unknown heading at x={indent}: {_text(line)!r}")
    return level, indent


def _cells(line: list[dict], page: int) -> dict[str, str]:
    edges = [x for _, x in _COLUMNS] + [_RIGHT_EDGE]
    cols: dict[str, list[dict]] = {name: [] for name, _ in _COLUMNS}
    for c in line:
        i = next((k for k in range(len(_COLUMNS) - 1, -1, -1) if edges[k] - _X_TOL <= c["x0"]), None)
        if i is None or c["x1"] > edges[i + 1] + _X_TOL:
            raise CatalogueError(f"page {page}: character {c['text']!r} at x={c['x0']:.1f} outside columns")
        cols[_COLUMNS[i][0]].append(c)
    return {name: _text(cs) for name, cs in cols.items()}


def _daily_cost_consistent(retail: float, ahd: float, khth: float) -> bool:
    """ΚΗΘ = ΛΙΑΝΙΚΗ / ΑΗΔ, with ΑΗΔ printed to 2 and ΚΗΘ to 3 decimals."""
    lo_ahd, hi_ahd = ahd - 0.005, ahd + 0.005
    lo_k, hi_k = max(khth - 0.0005, 1e-9), khth + 0.0005
    return retail / hi_k <= hi_ahd + 1e-9 and retail / lo_k >= lo_ahd - 1e-9


def _row(line: list[dict], page: int, list_name: str, decimal: str, groups) -> ReimbursementRow:
    cell = _cells(line, page)
    where = f"page {page}, row {cell['eof_code'] or _text(line)!r}"
    if not re.fullmatch(r"\d{9}", cell["eof_code"]):
        raise CatalogueError(f"{where}: ΚΩΔΙΚΟΣ {cell['eof_code']!r} is not 9 digits")

    def num(name: str) -> float:
        try:
            return parse_number(cell[name], decimal)
        except CatalogueError as e:
            raise CatalogueError(f"{where}, {name}: {e}") from None

    ddd, ahd, khth = num("ddd"), num("daily_doses_per_pack"), num("daily_cost")
    retail, reimb = num("retail_in_list"), num("reimbursement_price")
    if reimb <= 0:
        raise CatalogueError(f"{where}: reimbursement price {reimb} is not positive")
    if (ahd == 0) != (khth == 0):
        raise AmbiguousRow(f"ΑΗΔ {cell['daily_doses_per_pack']} and ΚΗΘ {cell['daily_cost']}: one is zero")
    if ahd and not _daily_cost_consistent(retail, ahd, khth):
        raise AmbiguousRow(f"ΚΗΘ {khth} != ΛΙΑΝΙΚΗ {retail} / ΑΗΔ {ahd}")
    if reimb > retail + 0.005:
        raise AmbiguousRow(f"reimbursement price {reimb} above retail {retail}")
    substance = groups["atc5"]
    if substance is None or substance.code != cell["atc"]:
        raise AmbiguousRow(f"ATC {cell['atc']!r} differs from heading {substance and substance.code!r}")
    route, group = groups["route"], groups["group"]
    return ReimbursementRow(
        eof_code=cell["eof_code"],
        list_name=list_name,
        atc=cell["atc"],
        name_pdf=cell["name_pdf"],
        dose_form=cell["dose_form"],
        strength=cell["strength"],
        pack=cell["pack"],
        dispensing=cell["dispensing"],
        mah_pdf=cell["mah_pdf"],
        ddd=ddd or None,
        ddd_unit=cell["ddd_unit"] or None,
        daily_doses_per_pack=ahd or None,
        daily_cost=khth or None,
        retail_in_list=retail,
        reimbursement_price=reimb,
        flag_s=cell["flag_s"],
        flag_t=cell["flag_t"],
        route_group=route.label if route else None,
        therapeutic_group=group.label if group else None,
        restrictions=[r for lvl in _LEVELS if groups[lvl] for r in groups[lvl].restrictions],
        page=page,
    )


def _blocks(pages):
    """Yield (page, kind, indent, lines); a note or heading wrapped over lines is one block.

    Blocks never continue across a page break (not seen in 10/2026): a note split there
    would become two notes of the same heading.
    """
    for page, lines in pages:
        prev = None
        for line in lines:
            kind, indent = _classify(line, page)
            if (
                prev is not None
                and kind == prev[1]
                and kind in ("restriction", "group", "route")
                and line[0]["top"] - prev[3][-1][0]["top"] < _WRAP_GAP
            ):
                prev[3].append(line)
                continue
            if prev is not None:
                yield prev
            prev = (page, kind, indent, [line])
        if prev is not None:
            yield prev


def _page_lines(path: Path):
    import pdfplumber  # optional dependency, only needed for PDF parsing

    with pdfplumber.open(path) as pdf:
        for n, p in enumerate(pdf.pages, start=1):
            chars = p.chars
            p.close()
            yield n, _lines(chars)


def read_catalogue(
    path: Path | str, list_name: str, decimal: str, issues: list[dict] | None = None
) -> list[ReimbursementRow]:
    """Parse one catalogue PDF.

    `decimal` is the decimal separator of this file ('.' for the main list of 10/2026,
    ',' for N3816). Rows with contradicting values are skipped and appended to `issues`
    (if given) for manual review; with issues=None they raise AmbiguousRow.
    """
    path = Path(path)
    if list_name not in LISTS:
        raise ValueError(f"list_name must be one of {LISTS}, not {list_name!r}")
    if decimal not in _NUMBER:
        raise ValueError(f"decimal must be '.' or ',', not {decimal!r}")
    try:
        return _parse(path, list_name, decimal, issues)
    except (CatalogueError, AmbiguousRow) as e:
        raise type(e)(f"{path.name}: {e}") from None


def _parse(path: Path, list_name: str, decimal: str, issues: list[dict] | None) -> list[ReimbursementRow]:
    def content():
        for page, lines in _page_lines(path):
            body, title = _strip_header(lines, page)
            if page == 1:
                is_n3816 = title is not None and re.search(r"[NΝ]\s*3816", title) is not None
                if title is None or is_n3816 != (list_name == "n3816"):
                    raise CatalogueError(f"title {title!r} does not match list {list_name!r}")
            yield page, body

    groups: dict[str, _Heading | None] = dict.fromkeys(_LEVELS)
    parent: str | None = None  # heading a restriction note right here would belong to
    out: list[ReimbursementRow] = []
    seen: dict[str, int] = {}
    for page, kind, indent, lines in _blocks(content()):
        text = " ".join(_text(line) for line in lines)
        if kind in _LEVELS:
            groups[kind] = _Heading(text)
            for lvl in _LEVELS[_LEVELS.index(kind) + 1 :]:
                groups[lvl] = None
            parent = kind
        elif kind == "restriction":
            if parent is None or _RESTRICTION_INDENT.get(parent) != indent:
                raise CatalogueError(
                    f"page {page}: restriction at x={indent} after {parent or 'a package row'}: {text!r}"
                )
            groups[parent].restrictions.append(text)
        else:
            parent = None
            try:
                row = _row(lines[0], page, list_name, decimal, groups)
            except AmbiguousRow as e:
                if issues is None:
                    raise AmbiguousRow(f"page {page}: {e}") from None
                cell = _cells(lines[0], page)
                issues.append(
                    {
                        "file": path.name,
                        "page": page,
                        "eof_code": cell["eof_code"],
                        "name": cell["name_pdf"],
                        "problem": str(e),
                    }
                )
                continue
            if row.eof_code in seen:
                raise CatalogueError(
                    f"ΚΩΔΙΚΟΣ {row.eof_code} on page {page} already on page {seen[row.eof_code]}"
                )
            seen[row.eof_code] = page
            out.append(row)
    if not out:
        raise CatalogueError("no package rows found")
    return out


CSV_FIELDS = [f.name for f in fields(ReimbursementRow)] + ["source_file", "moh_article", "published"]
RESTRICTION_SEP = " || "


def write_csv(
    rows: list[ReimbursementRow], out: Path, source_file: str, moh_article: str = "", published: str = ""
) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(CSV_FIELDS)
        for r in rows:
            rec = [getattr(r, f.name) for f in fields(ReimbursementRow)]
            rec[CSV_FIELDS.index("restrictions")] = RESTRICTION_SEP.join(r.restrictions)
            w.writerow(["" if v is None else v for v in rec] + [source_file, moh_article, published])


def main() -> None:
    ap = argparse.ArgumentParser(description="Parse a MoH reimbursement catalogue PDF into CSV.")
    ap.add_argument("--pdf", type=Path, required=True)
    ap.add_argument("--list", dest="list_name", choices=LISTS, required=True)
    ap.add_argument(
        "--decimal", choices=sorted(_NUMBER), required=True, help="decimal separator of this file"
    )
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--article", default="", help="MoH article id, written to every row as provenance")
    ap.add_argument("--published", default="", help="publication date (YYYY-MM-DD) of the article")
    args = ap.parse_args()
    issues: list[dict] = []
    rows = read_catalogue(args.pdf, args.list_name, args.decimal, issues)
    write_csv(rows, args.out, args.pdf.name, args.article, args.published)
    restricted = sum(1 for r in rows if r.restrictions)
    print(f"{args.pdf.name}: {len(rows)} rows ({restricted} with restrictions) -> {args.out}")
    print(f"issues: {len(issues)}")
    for i in issues:
        print(f"  page {i['page']} {i['eof_code']} {i['name']}: {i['problem']}")


if __name__ == "__main__":
    main()
