"""Links from our packages to the EMA product information in Greek (ΠΧΠ + ΦΟΧ).

Medicines authorised centrally (European Commission decision on an EMA opinion) have one
product-information PDF per product at the EMA: SmPC, labelling and package leaflet
together, in every EU language. For the packages of our price list that are such
products we store a link to the Greek PDF. We link; we do not copy or host the PDFs.

Sources, both from the EMA "Download medicine data" pages and regenerated by the EMA
every day:
  MEDICINES_XLSX  every medicine with an EPAR: name, product number, INN, status, MAH,
                  EPAR page URL (we keep human medicines with status "Authorised");
  DOCUMENTS_JSON  every EPAR document with its translations; gives the Greek PI URL.
Both are downloaded once into a cache directory (sha256 in its manifest.json);
--refresh downloads them again.

The Greek URL is read from the documents file, never guessed. Building
"<slug>-epar-product-information_el.pdf" from the EPAR page slug gives a wrong URL for a
few products (renamed products, file names without hyphens). When the documents file
has no Greek PI for a product, pi_el_url stays empty and only the EPAR page is linked.

A package is linked to an EMA product only when (never on the name alone):
  1. its brand, the words before the dose form (sitegen.drug.split_name), equals the EMA
     name or a "(previously ...)" name after name_key(): case, accents, ®/™, spaces and
     punctuation ignored, Greek capitals that look like Latin ones read as Latin;
  2. the active substances share a main word: EMA INN and active substance against our
     substances; salts and generic words (HYDROCHLORIDE, VACCINE, ...) do not count;
  3. the brand names exactly one EMA product. Otherwise: no link, listed in the report.

Usage:
    python -m ingest.ema --packages data/current/packages.csv --out data/current/ema_links.csv
    python -m ingest.ema ... --verify 5    # also check 5 Greek PI links, one at a time
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
import sys
import time
import unicodedata
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field, replace
from datetime import UTC, datetime
from pathlib import Path

import openpyxl
import requests

from sitegen.drug import split_name

EMA = "https://www.ema.europa.eu"
MEDICINES_XLSX = f"{EMA}/en/documents/report/medicines-output-medicines-report_en.xlsx"
DOCUMENTS_JSON = f"{EMA}/en/documents/report/documents-output-epar_documents_json-report_en.json"
EPAR_PREFIX = f"{EMA}/en/medicines/human/EPAR/"

PAUSE_SECONDS = 5.0  # the EMA answered 429 (too many requests) to HEAD requests 3 s apart
RETRIES = 3  # on 429/5xx/connection errors; waits Retry-After, else 30, 60, 120 s

LINK_FIELDS = ("eof_code", "ema_name", "ema_product_number", "inn", "pi_el_url", "epar_url", "matched_by")

# Columns read from the medicines table (header text -> field). A missing one is an error;
# other columns are ignored.
_COLUMNS = {
    "Category": "category",
    "Name of medicine": "name",
    "EMA product number": "product_number",
    "Medicine status": "status",
    "International non-proprietary name (INN) / common name": "inn",
    "Active substance": "active_substance",
    "Marketing authorisation developer / applicant / holder": "mah",
    "Medicine URL": "epar_url",
}
_CATEGORIES = {"Human", "Veterinary"}
_PRODUCT_NUMBER = re.compile(r"^EMEA/H/C/\d{6}$")
_SLUG = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")

# Notes the EMA appends to a name: "Tenkasi (previously Orbactiv)", "Briviact (in Italy: Nubriveo)".
_NAME_NOTE = re.compile(r"\s*\((?:previously\s[^)]*|in [A-Z][a-z]+:[^)]*)\)")
_PREVIOUSLY = re.compile(r"\(previously\s+([^)]*)\)")

# Greek capitals that look like Latin ones; price-list names mix the two (e.g. "ΒTx").
_LOOKALIKE = str.maketrans("ΑΒΕΖΗΙΚΜΝΟΡΤΥΧ", "ABEZHIKMNOPTYX")

# Words that do not identify a substance on their own: salts, hydrates, esters, and
# generic words of biologicals and vaccines. Words shorter than 4 letters never count.
_NOT_MAIN = frozenset(
    """
    ACETATE ACID ANHYDROUS ARGININE BESILATE BESYLATE BROMIDE CALCIUM CHLORIDE CITRATE
    DIHYDRATE DIHYDROCHLORIDE DIPROPIONATE DISODIUM ETEXILATE FUMARATE HEMIFUMARATE
    HEMIHYDRATE HYDRATE HYDROBROMIDE HYDROCHLORIDE HYDROGEN LACTATE LYSINE MAGNESIUM
    MALEATE MEDOXOMIL MESILATE MESYLATE MONOHYDRATE NITRATE PHOSPHATE POTASSIUM
    PROPIONATE SESQUIHYDRATE SODIUM SUCCINATE SULFATE SULPHATE TARTRATE TOSILATE
    TOSYLATE TRIHYDRATE
    ALFA BETA GAMMA PEGOL HUMAN RECOMBINANT
    ADSORBED ANTIGEN ATTENUATED CONJUGATE CONJUGATED INACTIVATED LIKE LIVE PURIFIED
    STRAIN SURFACE TOXOID TYPE VACC VACCINE VIRUS
    """.split()
)


class EmaFormatError(ValueError):
    """An EMA file does not look like the one this module was written for."""


@dataclass(frozen=True)
class EmaProduct:
    name: str  # as published, may end in "(previously ...)"
    product_number: str  # EMEA/H/C/002840
    inn: str  # INN / common name, ";" between substances
    active_substance: str
    mah: str
    epar_url: str
    pi_el_url: str = ""  # Greek product information, from the EPAR documents file

    @property
    def current_name(self) -> str:
        return _NAME_NOTE.sub("", self.name).strip()

    @property
    def previous_names(self) -> list[str]:
        return [m.strip() for m in _PREVIOUSLY.findall(self.name)]

    @property
    def slug(self) -> str:
        return self.epar_url.removeprefix(EPAR_PREFIX)


@dataclass(frozen=True)
class Link:
    eof_code: str
    product: EmaProduct
    matched_by: str  # "name+substance" or "previous_name+substance"


@dataclass
class Matches:
    links: list[Link] = field(default_factory=list)
    ambiguous: list[dict] = field(default_factory=list)  # brand names several EMA products
    name_only: list[dict] = field(default_factory=list)  # name matched, substances did not


# --- text --------------------------------------------------------------------------


def _fold(text: str) -> str:
    """Uppercase, no accents, no ®/™, Greek look-alike capitals as Latin."""
    t = unicodedata.normalize("NFKD", text.replace("®", " ").replace("™", " ")).upper()
    t = "".join(c for c in t if not unicodedata.combining(c))
    return t.translate(_LOOKALIKE)


def name_key(name: str) -> str:
    """'Abilify Maintena®', 'ABILIFY-MAINTENA', 'abilify maintena' -> 'ABILIFYMAINTENA'.

    Greek letters without a Latin look-alike stay, so a Greek name never shrinks to a
    Latin fragment of itself.
    """
    return "".join(re.findall(r"[A-Z0-9Α-Ω]+", _fold(name)))


def substance_words(text: str) -> set[str]:
    """Main words of a substance list: 'dalbavancin hydrochloride' -> {'DALBAVANCIN'}."""
    words = re.findall(r"[A-Z0-9]+", _fold(text))
    return {w for w in words if len(w) >= 4 and not w.isdigit() and w not in _NOT_MAIN}


# --- download ----------------------------------------------------------------------


def _retry_after(r: requests.Response, default: float) -> float:
    try:
        return min(float(r.headers.get("Retry-After", "")), 300.0)
    except ValueError:
        return default


class Client:
    """One request at a time, a pause between requests, backs off on 429 and 5xx."""

    def __init__(self, pause: float = PAUSE_SECONDS, session: requests.Session | None = None):
        self.s = session or requests.Session()
        self.pause = pause
        self._last = float("-inf")

    def request(self, method: str, url: str, **kw) -> requests.Response:
        for attempt in range(RETRIES + 1):
            wait = self.pause - (time.monotonic() - self._last)
            if wait > 0:
                time.sleep(wait)
            try:
                r = self.s.request(method, url, timeout=120, **kw)
            except (requests.ConnectionError, requests.Timeout):
                self._last = time.monotonic()
                if attempt == RETRIES:
                    raise
                time.sleep(30 * 2**attempt)
                continue
            self._last = time.monotonic()
            if (r.status_code == 429 or r.status_code >= 500) and attempt < RETRIES:
                r.close()
                time.sleep(_retry_after(r, 30 * 2**attempt))
                continue
            return r
        raise AssertionError("unreachable")


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _read_manifest(path: Path) -> list[dict]:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else []


def fetch(client: Client, url: str, cache_dir: Path, refresh: bool = False) -> Path:
    """The cached copy of `url`; downloads it when there is none or when `refresh`.

    Every download that differs from the previous one is kept as its own file (name +
    UTC time stamp), never overwritten, and recorded in cache_dir/manifest.json with its
    sha256. A refresh that brings the same bytes keeps the earlier file.
    """
    manifest_path = cache_dir / "manifest.json"
    manifest = _read_manifest(manifest_path)
    cached = [e for e in manifest if e["url"] == url and (cache_dir / e["file"]).exists()]
    if cached and not refresh:
        return cache_dir / cached[-1]["file"]
    cache_dir.mkdir(parents=True, exist_ok=True)
    stem, _, ext = url.rsplit("/", 1)[-1].rpartition(".")
    part = cache_dir / f"{stem}.{ext}.part"
    with client.request("GET", url, stream=True) as r:
        r.raise_for_status()
        stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
        with part.open("wb") as fh:
            for chunk in r.iter_content(1 << 16):
                fh.write(chunk)
        last_modified = r.headers.get("Last-Modified", "")
    digest = _sha256(part)
    if cached and cached[-1]["sha256"] == digest:
        part.unlink()
        return cache_dir / cached[-1]["file"]
    path = cache_dir / f"{stem}_{stamp}.{ext}"
    n = 1
    while path.exists():  # two downloads within one second
        n += 1
        path = cache_dir / f"{stem}_{stamp}-{n}.{ext}"
    part.replace(path)
    manifest.append(
        {
            "url": url,
            "file": path.name,
            "sha256": digest,
            "bytes": path.stat().st_size,
            "downloaded": stamp,
            "last_modified": last_modified,
        }
    )
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8")
    return path


# --- EMA files ---------------------------------------------------------------------


def _text(v: object) -> str:
    return " ".join(str(v).split()) if v is not None else ""


def read_medicines(path: Path) -> tuple[str, list[EmaProduct]]:
    """(generation time, human medicines with status Authorised) from the medicines table."""
    wb = openpyxl.load_workbook(path, read_only=True)
    try:
        rows = wb.worksheets[0].iter_rows(values_only=True)
        first = [_text(v) for v in next(rows, ())]
        if first[:2] != ["Content type:", "Medicine"] or len(first) < 4:
            raise EmaFormatError(f"{path.name}: not the EMA medicines table (first row {first[:4]})")
        generated = first[3]
        cols: dict[str, int] | None = None
        products: list[EmaProduct] = []
        for row in rows:
            texts = [_text(v) for v in row]
            if cols is None:
                if texts and texts[0] == "Category":
                    missing = [h for h in _COLUMNS if h not in texts]
                    if missing:
                        raise EmaFormatError(f"{path.name}: missing columns {missing}")
                    cols = {f: texts.index(h) for h, f in _COLUMNS.items()}
                continue
            rec = {f: texts[i] if i < len(texts) else "" for f, i in cols.items()}
            if not any(rec.values()):
                continue
            if rec["category"] not in _CATEGORIES:
                raise EmaFormatError(f"{path.name}: unknown category {rec['category']!r}")
            if rec["category"] == "Human" and rec["status"] == "Authorised":
                products.append(_product(rec, path))
    finally:
        wb.close()
    if cols is None:
        raise EmaFormatError(f"{path.name}: no header row")
    if not products:
        raise EmaFormatError(f"{path.name}: no authorised human medicines")
    numbers = [p.product_number for p in products]
    dupes = sorted({n for n in numbers if numbers.count(n) > 1})
    if dupes:
        raise EmaFormatError(f"{path.name}: product numbers listed twice: {dupes}")
    return generated, products


def _product(rec: dict[str, str], path: Path) -> EmaProduct:
    p = EmaProduct(
        name=rec["name"],
        product_number=rec["product_number"],
        inn=rec["inn"],
        active_substance=rec["active_substance"],
        mah=rec["mah"],
        epar_url=rec["epar_url"],
    )
    if not p.name or not _PRODUCT_NUMBER.match(p.product_number):
        raise EmaFormatError(f"{path.name}: bad name/product number {p.name!r} {p.product_number!r}")
    if not p.epar_url.startswith(EPAR_PREFIX) or not _SLUG.match(p.slug):
        raise EmaFormatError(f"{path.name}: unexpected EPAR URL {p.epar_url!r}")
    return p


def read_pi_urls(path: Path) -> tuple[str, dict[str, str], dict[str, str]]:
    """(time stamp, {product number: Greek PI URL}, {medicine name: Greek PI URL}).

    Only documents of type product-information whose name ends in "Product information"
    (this leaves out drafts "as approved by the CHMP" and the member-state URL list).
    A product number or name with more than one Greek URL is left out.
    """
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
        stamp, items = doc["meta"]["timestamp"], doc["data"]
    except (KeyError, TypeError, json.JSONDecodeError) as e:
        raise EmaFormatError(f"{path.name}: not the EMA EPAR documents file ({e})") from e
    by_number: dict[str, set[str]] = {}
    by_name: dict[str, set[str]] = {}
    for d in items:
        if d.get("type") != "product-information":
            continue
        if not str(d.get("name", "")).strip().lower().endswith("product information"):
            continue
        el = ((d.get("translations") or {}).get("el") or "").strip()
        if not el.startswith(f"{EMA}/el/"):
            continue
        by_number.setdefault(str(d.get("ema_product_number", "")).strip(), set()).add(el)
        by_name.setdefault(str(d.get("medicine_name", "")).strip(), set()).add(el)
    if not by_number:
        raise EmaFormatError(f"{path.name}: no Greek product information documents")

    def unique(m: dict[str, set[str]]) -> dict[str, str]:
        return {k: next(iter(v)) for k, v in m.items() if k and len(v) == 1}

    return stamp, unique(by_number), unique(by_name)


def attach_pi(
    products: list[EmaProduct], by_number: Mapping[str, str], by_name: Mapping[str, str]
) -> list[EmaProduct]:
    """Set pi_el_url by product number, else by exact medicine name (the documents file
    carries an older product number for a few products), else leave it empty."""
    return [
        replace(p, pi_el_url=by_number.get(p.product_number) or by_name.get(p.name) or "") for p in products
    ]


# --- matching ----------------------------------------------------------------------


def read_packages(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    need = {"eof_code", "name", "substances"}
    if rows and not need <= rows[0].keys():
        raise ValueError(f"{path}: missing columns {sorted(need - rows[0].keys())}")
    return rows


def match_packages(packages: Iterable[Mapping[str, str]], products: Iterable[EmaProduct]) -> Matches:
    products = list(products)
    index: dict[str, dict[str, tuple[EmaProduct, str]]] = {}
    for p in products:
        index.setdefault(name_key(p.current_name), {})[p.product_number] = (p, "name")
    for p in products:
        for alias in p.previous_names:
            index.setdefault(name_key(alias), {}).setdefault(p.product_number, (p, "previous_name"))
    out = Matches()
    for pkg in packages:
        brand = split_name(pkg["name"])[0]
        key = name_key(brand)
        cands = index.get(key) if key else None
        if not cands:
            continue
        row = {"eof_code": pkg["eof_code"], "name": pkg["name"], "brand": brand}
        if len(cands) > 1:
            out.ambiguous.append(
                row
                | {"candidates": sorted(f"{p.product_number} {p.current_name}" for p, _ in cands.values())}
            )
            continue
        ((p, how),) = cands.values()
        ours = substance_words(pkg.get("substances", "").replace("|", " "))
        if ours & substance_words(f"{p.inn} {p.active_substance}"):
            out.links.append(Link(pkg["eof_code"], p, f"{how}+substance"))
        else:
            out.name_only.append(
                row
                | {
                    "substances": pkg.get("substances", ""),
                    "ema": f"{p.product_number} {p.current_name}",
                    "ema_substances": f"{p.inn} / {p.active_substance}",
                }
            )
    return out


def write_links(links: Iterable[Link], out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(LINK_FIELDS)
        for k in sorted(links, key=lambda k: k.eof_code):
            p = k.product
            w.writerow(
                [k.eof_code, p.current_name, p.product_number, p.inn, p.pi_el_url, p.epar_url, k.matched_by]
            )


# --- verification ------------------------------------------------------------------


def spread(urls: Iterable[str], n: int) -> list[str]:
    """n of the distinct URLs, spread evenly over their sorted list (deterministic)."""
    u = sorted(set(urls))
    return u if n >= len(u) else [u[i * len(u) // n] for i in range(n)]


def verify(client: Client, urls: Iterable[str]) -> list[tuple[str, str]]:
    """HEAD each URL (one at a time, client pause between); failures as (url, reason)."""
    failures = []
    for url in urls:
        try:
            r = client.request("HEAD", url, allow_redirects=True)
            r.close()
        except requests.RequestException as e:
            failures.append((url, type(e).__name__))
            continue
        ctype = r.headers.get("Content-Type", "")
        if r.status_code != 200 or "pdf" not in ctype:
            failures.append((url, f"HTTP {r.status_code} {ctype}".strip()))
    return failures


# --- command line ------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Link packages to the EMA product information in Greek.")
    ap.add_argument("--packages", type=Path, default=Path("data/current/packages.csv"))
    ap.add_argument("--out", type=Path, default=Path("data/current/ema_links.csv"))
    ap.add_argument("--cache", type=Path, default=Path("data/ema"), help="where the EMA files are kept")
    ap.add_argument("--refresh", action="store_true", help="download the EMA files again")
    ap.add_argument("--medicines", type=Path, help="EMA medicines xlsx to use instead of the cache")
    ap.add_argument("--documents", type=Path, help="EMA EPAR documents json to use instead of the cache")
    ap.add_argument(
        "--verify", type=int, default=0, metavar="N", help="check N Greek PI links, one request at a time"
    )
    args = ap.parse_args(argv)

    client = Client()
    med_path = args.medicines or fetch(client, MEDICINES_XLSX, args.cache, args.refresh)
    doc_path = args.documents or fetch(client, DOCUMENTS_JSON, args.cache, args.refresh)
    generated, products = read_medicines(med_path)
    stamp, by_number, by_name = read_pi_urls(doc_path)
    products = attach_pi(products, by_number, by_name)
    m = match_packages(read_packages(args.packages), products)
    write_links(m.links, args.out)

    linked = {k.product.product_number: k.product for k in m.links}
    report = {
        "sources": [
            {
                "url": MEDICINES_XLSX,
                "file": med_path.name,
                "sha256": _sha256(med_path),
                "generated": generated,
            },
            {"url": DOCUMENTS_JSON, "file": doc_path.name, "sha256": _sha256(doc_path), "generated": stamp},
        ],
        "ema_authorised_products": len(products),
        "ema_products_with_pi_el": sum(1 for p in products if p.pi_el_url),
        "packages_linked": len(m.links),
        "products_linked": len(linked),
        "linked_products_without_pi_el": sorted(
            f"{p.product_number} {p.current_name}" for p in linked.values() if not p.pi_el_url
        ),
        "ambiguous": m.ambiguous,
        "name_only_rejected": m.name_only,
    }
    report_path = args.out.with_name(args.out.stem + "_report.json")
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=1), encoding="utf-8")

    with_pi, linked_without_pi = report["ema_products_with_pi_el"], report["linked_products_without_pi_el"]
    print(f"EMA authorised human products: {len(products)} ({with_pi} with Greek PI)")
    print(f"packages linked: {len(m.links)} -> {args.out}")
    print(f"distinct products linked: {len(linked)} ({len(linked_without_pi)} without Greek PI)")
    print(f"ambiguous (no link): {len(m.ambiguous)} packages")
    print(f"name matched, substances did not (no link): {len(m.name_only)} packages")
    print(f"report: {report_path}")

    if args.verify:
        urls = spread((p.pi_el_url for p in linked.values() if p.pi_el_url), args.verify)
        failures = verify(client, urls)
        print(f"verified {len(urls)} Greek PI links: {len(urls) - len(failures)} ok, {len(failures)} failed")
        for url, why in failures:
            print(f"  FAILED {why}: {url}")
        if failures:
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
